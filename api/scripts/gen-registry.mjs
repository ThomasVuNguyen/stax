// Generates src/generated/registry.ts, which imports every *Controller.ts (routes), jobs.ts
// (queue handlers) and cron.ts (scheduled tasks) under src/. Run before dev/deploy/typecheck.
import { readdirSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("../src/", import.meta.url).pathname;
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) {
      if (name !== "generated") walk(p);
    } else files.push(p);
  }
})(root);

const rel = (p) => "../" + relative(root, p).replace(/\.ts$/, "");
const controllers = files.filter((f) => /Controller\.ts$/.test(f));
const jobs = files.filter((f) => /\/jobs\.ts$/.test(f));
const crons = files.filter((f) => /\/cron\.ts$/.test(f));

const lines = ["// Generated by scripts/gen-registry.mjs. Do not edit.", 'import type { Hono } from "hono";', 'import type { AppEnv, Env } from "../env";'];
controllers.forEach((f, i) => lines.push(`import c${i} from "${rel(f)}";`));
jobs.forEach((f) => lines.push(`import "${rel(f)}";`));
crons.forEach((f, i) => lines.push(`import * as cron${i} from "${rel(f)}";`));
lines.push("", `export const controllers: Hono<AppEnv>[] = [${controllers.map((_, i) => `c${i}`).join(", ")}];`);
lines.push(`export const crons: { scheduled(env: Env, exec: ExecutionContext): Promise<void> }[] = [${crons.map((_, i) => `cron${i}`).join(", ")}];`, "");
mkdirSync(join(root, "generated"), { recursive: true });
writeFileSync(join(root, "generated/registry.ts"), lines.join("\n"));
console.log(`registry: ${controllers.length} controllers, ${jobs.length} job modules, ${crons.length} cron modules`);
